"""
Generates resources/css/dark.css from Tailwind's default palette.

Dark mode works by re-pointing palette variables under `.dark` instead of
adding `dark:` classes to every component:
  - slate/gray scales are mirrored (50 <-> 950, 100 <-> 900, ...), so light
    surfaces become dark and dark text becomes light with the same contrast;
  - colored tints (50/100/200, used for chips and soft backgrounds) become
    translucent dark tints; brand shades 300-950 stay, so buttons keep
    their colors;
  - colored text 600-950 is lightened so it stays readable on dark;
  - white surfaces, borders and gradients get a dark surface color.

Run after changing the palette or the rules:  python scripts/generate-dark-theme.py
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
THEME = ROOT / 'node_modules' / 'tailwindcss' / 'theme.css'
OUT = ROOT / 'resources' / 'css' / 'dark.css'

NEUTRALS = ['slate', 'gray']
HUES = ['red', 'orange', 'amber', 'yellow', 'lime', 'green', 'emerald', 'teal', 'cyan',
        'sky', 'blue', 'indigo', 'violet', 'purple', 'fuchsia', 'pink', 'rose']
SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]

# Card/panel color: between the page (slate-950) and chips (slate-900).
SURFACE = 'oklch(17.5% 0.042 265)'
SURFACE_HOVER = 'oklch(22% 0.042 265)'

COLOR_VAR = r'--color-([a-z]+)-(\d+):\s*([^;]+);'
palette = {(m.group(1), int(m.group(2))): m.group(3) for m in re.finditer(COLOR_VAR, THEME.read_text(encoding='utf-8'))}
# The app's own brand scale (resources/css/app.css @theme): 50-700 only.
APP_CSS = ROOT / 'resources' / 'css' / 'app.css'
brand = {int(m.group(2)): m.group(3) for m in re.finditer(COLOR_VAR, APP_CSS.read_text(encoding='utf-8')) if m.group(1) == 'brand'}

out = ['/* Generated by scripts/generate-dark-theme.py - do not edit by hand. */', '']

out.append('.dark {')
out.append('    color-scheme: dark;')
for name in NEUTRALS:
    for shade in SHADES:
        mirror = SHADES[len(SHADES) - 1 - SHADES.index(shade)]
        out.append(f'    --color-{name}-{shade}: {palette[(name, mirror)]};')
tints = {50: (950, 55), 100: (900, 55), 200: (800, 55)}
for hue in HUES:
    for shade, (source, percent) in tints.items():
        out.append(f'    --color-{hue}-{shade}: color-mix(in oklab, {palette[(hue, source)]} {percent}%, transparent);')
for shade, (source, percent) in tints.items():
    out.append(f'    --color-brand-{shade}: color-mix(in oklab, {brand[700]} {percent - 20}%, transparent);')
# Brand ink (titles on the sign-in pages) is a text color: light in dark mode.
out.append(f'    --color-ink: {palette[("slate", 100)]};')
out.append('}')
out.append('')

out.append('.dark body {')
out.append('    background-color: var(--color-slate-50);')
out.append('    color: var(--color-slate-900);')
out.append('}')
out.append('')

# Colored text: lighter shade of the same hue (light-mode values, read from
# the palette so the remapped tints above are never used for text).
text_map = {600: 400, 700: 300, 800: 200, 900: 200, 950: 100}
for hue in HUES:
    for shade, lighter in text_map.items():
        color = palette[(hue, lighter)]
        cls = f'text-{hue}-{shade}'
        out.append(
            f'.dark [class~="{cls}"], .dark [class~="hover:{cls}"]:hover, '
            f'.dark .group:hover [class~="group-hover:{cls}"] {{ color: {color}; }}'
        )
        # With an opacity suffix (text-blue-700/80): same shade, ~80%.
        out.append(f'.dark [class*="{cls}/"] {{ color: color-mix(in oklab, {color} 80%, transparent); }}')
for shade, lighter in {600: 400, 700: 300}.items():
    cls = f'text-brand-{shade}'
    out.append(
        f'.dark [class~="{cls}"], .dark [class~="hover:{cls}"]:hover, '
        f'.dark .group:hover [class~="group-hover:{cls}"] {{ color: {brand[lighter]}; }}'
    )
out.append('')

out.append('/* White surfaces, glass borders and gradients. */')
out.append(f'.dark [class~="bg-white"] {{ background-color: {SURFACE}; }}')
out.append(f'.dark [class*="bg-white/"] {{ background-color: color-mix(in oklab, {SURFACE} 88%, transparent); }}')
out.append(f'.dark [class~="hover:bg-white"]:hover, .dark [class*="hover:bg-white/"]:hover {{ background-color: {SURFACE_HOVER}; }}')
out.append(f'.dark [class*="from-white"] {{ --tw-gradient-from: {SURFACE}; }}')
out.append(f'.dark [class*="via-white"] {{ --tw-gradient-via: {SURFACE}; }}')
out.append(f'.dark [class*="to-white"] {{ --tw-gradient-to: {SURFACE}; }}')
out.append('.dark [class*="border-white"] { border-color: rgb(255 255 255 / 0.08); }')
out.append('.dark [class*="ring-white"] { --tw-ring-color: rgb(255 255 255 / 0.1); }')
out.append('.dark [class*="divide-white"] > :not(:last-child) { border-color: rgb(255 255 255 / 0.08); }')
out.append(f'.dark [class~="text-black"] {{ color: {palette[("slate", 100)]}; }}')
out.append('')

OUT.write_text('\n'.join(out) + '\n', encoding='utf-8')
print(f'wrote {OUT.relative_to(ROOT)} ({len(out)} lines)')
